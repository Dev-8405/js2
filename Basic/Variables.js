// variable

// Variable ek container hai jo data store karta hai.

// 1. var

// var se variable create kar sakte hain aur uski value change bhi kar sakte hain.

var name ="dev"
console.log(name);

name ="rahul"
console.log(name);

// 2. let 
// let se bhi variable create kar sakte hain aur value change kar sakte hain.

let age =22;
console.log(age);

age =25;
console.log(age);

// 3. const

// const se variable create karte hain, lekin usko dobara assign nahi kar sakte.

const city="mumbai";
console.log(city);